#!/usr/bin/env node
import {writeFileSync} from 'node:fs';
const raw = process.env.API_BASE_URL;
if (!raw) throw new Error('API_BASE_URL must be the deployed HTTPS backend origin.');
const url = new URL(raw);
if (url.protocol !== 'https:' || url.username || url.password || url.search || url.hash || url.pathname !== '/') {
  throw new Error('API_BASE_URL must be an HTTPS origin without credentials, path or query.');
}
writeFileSync('src/environments/environment.prod.ts', `// Generated by scripts/configure-hosting.mjs for this build only.\nexport const environment = { production: true, apiBaseUrl: ${JSON.stringify(url.origin)}, hostedTest: ${process.env.HOSTED_TEST === '1'} };\n`);
